const note = ([pitch, start, len = 1, vel = 0.8]: NoteSpec): Note => ({
  pitch,
  start,
  len,
  vel,
});
const notes = (...items: NoteSpec[]): Note[] => items.map(note);
const pattern = (
  id: string,
  name: string,
  steps: number,
  color: string,
  tracks: TrackNotes,
): Pattern => ({
  id,
  name,
  steps,
  color,
  tracks: Object.fromEntries(
    Object.entries(tracks).map(([instrument, part]) => [
      instrument,
      notes(...part),
    ]),
  ),
});
const instrument = (
  id: string,
  name: string,
  color: string,
  params: Partial<InstrumentParams>,
): Instrument => ({
  id,
  name,
  color,
  params: ensurePartials({ ...DEFAULT_PARAMS, ...params }),
});
const tracks = (names: string[]): Track[] =>
  names.map((name, index) => ({ name, color: COLORS[index % COLORS.length] }));
const clip = (
  id: string,
  patternId: string,
  track: number,
  start: number,
  len: number,
  transpose?: number,
) => ({
  id,
  patternId,
  track,
  start,
  len,
  ...(transpose ? { transpose } : {}),
});
type ArrangementSection = readonly (readonly [
  patternId: string,
  track: number,
])[];
const arrangeSong = (
  prefix: string,
  sections: ArrangementSection[],
): Project["arrangement"] =>
  sections.flatMap((section, sectionIndex) =>
    section.map(([patternId, track], layerIndex) =>
      clip(
        `${prefix}${sectionIndex + 1}-${layerIndex + 1}`,
        patternId,
        track,
        sectionIndex * 32,
        32,
      ),
    ),
  );
const project = (
  instruments: Instrument[],
  patterns: Pattern[],
  arrangement: Project["arrangement"],
  laneNames: string[],
  bpm: number,
  automation: AutomationLane[],
  swing = 0,
): Project => {
  const instrumentIds = new Map(
    instruments.map((instrument) => [instrument.id, createId()]),
  );
  const patternIds = new Map(
    patterns.map((pattern) => [pattern.id, createId()]),
  );
  const automationIds = new Map(
    automation.map((lane) => [lane.id, createId()]),
  );
  const remapInstrumentId = (id: string): string => instrumentIds.get(id) || id;
  const remapPatternId = (id: string): string => patternIds.get(id) || id;

  return {
    formatVersion: PROJECT_FORMAT_VERSION,
    instruments: instruments.map((instrument) => ({
      ...instrument,
      id: remapInstrumentId(instrument.id),
    })),
    patterns: patterns.map((pattern) => ({
      ...pattern,
      id: remapPatternId(pattern.id),
      tracks: Object.fromEntries(
        Object.entries(pattern.tracks).map(([id, notes]) => [
          remapInstrumentId(id),
          notes,
        ]),
      ),
    })),
    arrangement: arrangement.map((clip) => ({
      ...clip,
      id: createId(),
      patternId: remapPatternId(clip.patternId),
    })),
    tracks: tracks(laneNames),
    bpm,
    swing,
    automation: automation.map((lane) => ({
      ...lane,
      id: automationIds.get(lane.id)!,
      target:
        lane.target === "master" ? lane.target : remapInstrumentId(lane.target),
    })),
    automationOrder: automation.map((lane) => automationIds.get(lane.id)!),
    automationPositions: {},
    zoom: { seq: { width: 24, height: 14 }, arr: { width: 24, height: 32 } },
  };
};
const connect = (
  patterns: Pattern[],
  patternId: string,
  instrumentId: string,
  from: number,
  to: number,
  curve: CurveShape,
) => {
  const part = patterns.find((value) => value.id === patternId)?.tracks[
    instrumentId
  ];
  const source = part?.find((value) => value.start === from);
  const target = part?.find((value) => value.start === to);
  if (!source || !target || target.start < source.start + source.len) {
    throw new Error(
      `Invalid legato link in ${patternId}/${instrumentId}: ${from} -> ${to}`,
    );
  }
  source.legatoTo = { pitch: target.pitch, start: target.start, curve };
};

