export const DEFAULT_SHAPE = PARTIAL_SHAPES[0].name;

export function findShape(name: string | undefined): PartialShape {
    return PARTIAL_SHAPES.find(s => s.name === name) || PARTIAL_SHAPES[0];
}

// The generator settings, as remembered on the instrument
export interface HarmonicsGen {
    shape: string;
    count: number;
    falloff: number; // extra tilt on top of the shape's own weights (1 = none)
    stretch: number; // inharmonicity: ratio → ratio^(1+stretch)
}

export function genSettings(p: InstrumentParams): HarmonicsGen {
    return {
        shape: p.harmShape || DEFAULT_SHAPE,
        count: Math.round(p.harm),
        falloff: p.falloff,
        stretch: p.stretch,
    };
}

// Generate a partial profile — the "initial set of values" of the editor.
export function genPartials(g: HarmonicsGen): PartialSpec[] {
    const shape = findShape(g.shape);
    const n = Math.max(1, Math.min(shape.max, MAX_PARTIALS, Math.round(g.count)));
    return Array.from({ length: n }, (_, i) => {
        const base = shape.partial(i + 1);
        return {
            ratio: r3(Math.pow(base.ratio, 1 + g.stretch)),
            level: l2(base.level * Math.pow(g.falloff, i)),
        };
    });
}

// Make sure an instrument has an explicit profile (fresh instruments, presets
// and loaded projects that only carry the generator values).
export function ensurePartials(p: InstrumentParams): InstrumentParams {
    if (!p.partials || !p.partials.length) {
        p.partials = genPartials(genSettings(p));
    }
    return p;
}

