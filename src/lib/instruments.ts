/* ---- harmonics: the partial profile of an instrument ----
 * A timbre is defined by its partial *set*, not by "contiguous partials with
 * a falling amplitude": an organ registration is 1 2 3 4 6 8 at comparable
 * levels (no 5th, no 7th), a clarinet is odd-only, a bell is inharmonic.
 * Every instrument therefore carries an explicit `partials` list, which is
 * hand-edited in the harmonics editor and (re-)generated by the generator
 * dialog from a shape + count + falloff + stretch (those four values are
 * remembered per instrument in harmShape/harm/falloff/stretch). */
export const MAX_PARTIALS = 16;

const r3 = (v: number): number => Math.round(v * 1000) / 1000;
const l2 = (v: number): number => Math.max(0, Math.min(1, Math.round(v * 100) / 100));

export const clampPartialLevel = (level: number): number => l2(level);

export interface PartialShape {
    name: string;
    max: number; // how many partials this shape can produce
    partial: (h: number) => PartialSpec; // h = 1-based partial index
}

const fn = (
    name: string,
    max: number,
    ratio: (h: number) => number,
    weight: (h: number) => number,
): PartialShape => ({ name, max, partial: h => ({ ratio: r3(ratio(h)), level: l2(weight(h)) }) });
const tbl = (name: string, ratios: number[], weights: number[]): PartialShape => ({
    name,
    max: ratios.length,
    partial: h => ({ ratio: r3(ratios[h - 1]), level: l2(weights[h - 1]) }),
});

// Timbre families used as generator starting points
