/* ---- user presets (saved in the browser) ----
 * The built-in PRESETS are the factory bank; anything the user dials in can be
 * stored next to them under its own name and shows up in the preset picker. */
const USER_PRESET_KEY = 'pinky-presets-v1';

export type PresetBank = Record<string, Partial<InstrumentParams>>;

export function loadUserPresets(): PresetBank {
    try {
        const raw = localStorage.getItem(USER_PRESET_KEY);
        // eslint-disable-next-line @typescript-eslint/no-unsafe-assignment
        const b = raw ? JSON.parse(raw) : null;
        return b && typeof b === 'object' ? (b as PresetBank) : {};
        // eslint-disable-next-line @typescript-eslint/no-unused-vars
    } catch (e) {
        return {};
    }
}

function storeUserPresets(bank: PresetBank): void {
    try {
        localStorage.setItem(USER_PRESET_KEY, JSON.stringify(bank));
        // eslint-disable-next-line @typescript-eslint/no-unused-vars
    } catch (e) {
        /* private mode / quota — presets are a convenience */
    }
}

// A preset is a full parameter snapshot (partials included) minus the identity
export function saveUserPreset(name: string, params: InstrumentParams): PresetBank {
    const bank = loadUserPresets();
    bank[name] = JSON.parse(JSON.stringify(params)) as Partial<InstrumentParams>;
    storeUserPresets(bank);
    return bank;
}

export function deleteUserPreset(name: string): PresetBank {
    const bank = loadUserPresets();
    delete bank[name];
    storeUserPresets(bank);
    return bank;
}

let nextColorIndex = 0;

export function createInstrument(name: string, preset: Partial<InstrumentParams> = {}): Instrument {
    const color = INSTRUMENT_COLORS[nextColorIndex++ % INSTRUMENT_COLORS.length];
    return {
        id: createId(),
        name,
        color,
        params: ensurePartials({ ...DEFAULT_PARAMS, ...preset }),
    };
}
